import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
const root=path.resolve(import.meta.dirname,'..');
const file=path.join(root,'data/dubai-south-floorplan-register.json');
const data=JSON.parse(await fs.readFile(file,'utf8'));
const project=data.projects.find(p=>p.id==='expo-valley-views');
const sourceUrl='https://www.expocitydubai.com/en/live/expo-valley-views/';
const page=await fetch(sourceUrl,{signal:AbortSignal.timeout(20000)});
if(!page.ok)throw new Error(`Source unavailable: ${page.status}`);
const html=await page.text();
const url=[...html.matchAll(/(?:src|href)="([^"]+)"/g)].map(m=>m[1]).find(u=>u.includes('Foor_plan-1_bed.jpg'));
if(!url)throw new Error('Official one-bedroom image is no longer published');
const remoteUrl=url.replaceAll('&amp;','&').split('?')[0];
const response=await fetch(remoteUrl,{signal:AbortSignal.timeout(20000)});
if(!response.ok||!response.headers.get('content-type')?.startsWith('image/'))throw new Error('Not an image');
const bytes=Buffer.from(await response.arrayBuffer());
const localUrl='/projects/dubai-south-floorplan-review/expo-valley-views-1.jpg';
await fs.writeFile(path.join(root,'public',localUrl),bytes);
Object.assign(project,{sourceUrl,sourceLabel:'Expo City Dubai official project page',checkedAt:new Date().toISOString(),qualification:'Official published one-bedroom project layout. Selected unit, building, area and dimensions require confirmation.',reviewPlans:[{remoteUrl,localUrl,bedrooms:1,areaSqft:null,layout:'Official 1-bedroom layout',sha256:crypto.createHash('sha256').update(bytes).digest('hex'),reviewStatus:'pending-visual-review',matchStatus:'project-reference'}]});
await fs.writeFile(file,JSON.stringify(data,null,2)+'\n');
console.log(path.join(root,'public',localUrl));
